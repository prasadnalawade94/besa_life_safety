          <ul class="spec-list">
            <li><strong>PRESS HERE:</strong> Press the red emergency button to activate the Talk Back communication from that zone.</li>
            <li><strong>PUSH TO TALK:</strong> Follow the panel marking while speaking into the built-in MIC.</li>
            <li><strong>MIC:</strong> Speak clearly near the microphone opening for two-way communication with the control panel.</li>
            <li><strong>Green LED:</strong> Check the illuminated indicator for the unit power or operating status.</li>
            <li><strong>Main control panel:</strong> Silent, Reset, Test and All Call functions are operated from the main control panel, not from this zone cover.</li>
          </ul>

          <h4>LED Indicators</h4>
